//! ConVar metadata. `catalog/catalog.toml` is generated from
//! `research/data/convar_catalog.csv` plus `catalog/curated.toml` and embedded at build.

use std::collections::{BTreeMap, BTreeSet};
use std::sync::OnceLock;

use crate::preset::PresetId;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ApplyClass {
    Live,
    LiveCheat,
    Restart,
}

#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case", tag = "type")]
pub enum Kind {
    Bool,
    Int,
    Float,
    Enum { options: Vec<String> },
    String,
}

#[derive(
    Clone,
    Copy,
    Debug,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Default,
    serde::Serialize,
    serde::Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum Impact {
    High,
    Medium,
    Low,
    #[default]
    Unknown,
}

#[derive(Clone, Debug, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct CatalogEntry {
    pub category: String,
    #[serde(flatten)]
    pub kind: Kind,
    pub range: Option<[f64; 2]>,
    pub step: Option<f64>,
    pub default: Option<String>,
    pub apply: ApplyClass,
    #[serde(default)]
    pub impact: Impact,
    #[serde(default)]
    pub denylist: bool,
    /// The engine flags it `gameinfo_cannot_override`: a `gameinfo.gi` line for it is ignored.
    #[serde(default)]
    pub gameinfo_ignored: bool,
    #[serde(default)]
    pub notes: String,
    /// Raw value per preset; a leading `//` means present but commented out.
    #[serde(default)]
    pub presets: BTreeMap<PresetId, String>,
}

#[derive(Clone, Debug, Default)]
pub struct Catalog {
    pub entries: BTreeMap<String, CatalogEntry>,
}

#[derive(Debug, thiserror::Error)]
pub enum CatalogError {
    #[error("csv: {0}")]
    Csv(#[from] csv::Error),
    #[error("toml: {0}")]
    TomlDe(#[from] toml::de::Error),
    #[error("toml: {0}")]
    TomlSer(#[from] toml::ser::Error),
    #[error("csv has no `{0}` column")]
    MissingColumn(String),
    #[error("curated.toml: {0}")]
    Curated(String),
}

impl Catalog {
    pub fn embedded() -> &'static Catalog {
        static CATALOG: OnceLock<Catalog> = OnceLock::new();
        CATALOG.get_or_init(|| {
            Catalog::from_toml(include_str!("../../../catalog/catalog.toml")).expect(
                "embedded catalog.toml is checked by embedded_catalog_matches_a_fresh_generate",
            )
        })
    }

    pub fn from_toml(text: &str) -> Result<Catalog, CatalogError> {
        Ok(Catalog {
            entries: toml::from_str(text)?,
        })
    }

    pub fn get(&self, name: &str) -> Option<&CatalogEntry> {
        self.entries.get(name)
    }

    /// Case-insensitive match on name, category and notes.
    pub fn search<'a>(
        &'a self,
        query: &'a str,
    ) -> impl Iterator<Item = (&'a str, &'a CatalogEntry)> + 'a {
        let query = query.to_lowercase();
        self.entries
            .iter()
            .filter(move |(name, e)| {
                [name.as_str(), e.category.as_str(), e.notes.as_str()]
                    .iter()
                    .any(|f| f.to_lowercase().contains(&query))
            })
            .map(|(name, e)| (name.as_str(), e))
    }

    pub fn categories(&self) -> Vec<&str> {
        let set: BTreeSet<&str> = self.entries.values().map(|e| e.category.as_str()).collect();
        set.into_iter().collect()
    }

    /// Unlisted convars are allowed but treated as `Restart`.
    pub fn apply_class(&self, name: &str) -> ApplyClass {
        self.get(name).map_or(ApplyClass::Restart, |e| e.apply)
    }

    pub fn is_denied(&self, name: &str) -> bool {
        self.get(name).is_some_and(|e| e.denylist)
    }

    pub fn is_gameinfo_ignored(&self, name: &str) -> bool {
        self.get(name).is_some_and(|e| e.gameinfo_ignored)
    }
}

/// Builds catalog.toml text from the research CSV and the hand-curated overlay.
pub fn generate(csv: &str, curated: &str) -> Result<String, CatalogError> {
    let mut entries = entries_from_csv(csv)?;
    let overlay: BTreeMap<String, Curated> = toml::from_str(curated)?;
    for (name, c) in overlay {
        let entry = entries
            .get_mut(&name)
            .ok_or_else(|| CatalogError::Curated(format!("{name} is not in the csv")))?;
        c.apply_to(entry)
            .map_err(|msg| CatalogError::Curated(format!("{name}: {msg}")))?;
    }
    Ok(format!(
        "# Generated by `cargo run -p dt-core --example gen_catalog`. Edit catalog/curated.toml instead.\n\n{}",
        toml::to_string(&entries)?
    ))
}

fn entries_from_csv(csv: &str) -> Result<BTreeMap<String, CatalogEntry>, CatalogError> {
    let mut reader = csv::Reader::from_reader(csv.as_bytes());
    let headers = reader.headers()?.clone();
    let col = |name: &str| {
        headers
            .iter()
            .position(|h| h == name)
            .ok_or_else(|| CatalogError::MissingColumn(name.to_string()))
    };
    let name_col = col("name")?;
    let apply_col = col("apply_class")?;
    let flags_col = col("flags")?;
    let default_col = col("engine_default")?;
    let desc_col = col("engine_description")?;
    let comment_col = col("preset_comment(first seen)")?;
    let preset_cols = crate::preset::all()
        .iter()
        .map(|p| Ok((p.id, col(p.id.key())?)))
        .collect::<Result<Vec<_>, CatalogError>>()?;

    let mut entries = BTreeMap::new();
    for record in reader.records() {
        let record = record?;
        let cell = |i: usize| record.get(i).unwrap_or("").trim();
        let name = cell(name_col);
        let meta = crate::gi::parse_comment_meta(cell(comment_col));
        let default = Some(cell(default_col))
            .filter(|d| !d.is_empty())
            .map(str::to_string)
            .or(meta.default);
        let presets: BTreeMap<PresetId, String> = preset_cols
            .iter()
            .filter(|(_, i)| !cell(*i).is_empty())
            .map(|(id, i)| (*id, cell(*i).to_string()))
            .collect();
        let kind = infer_kind(
            presets
                .values()
                .map(String::as_str)
                .chain(default.as_deref()),
        );
        let description = Some(cell(desc_col))
            .filter(|d| !d.is_empty())
            .unwrap_or(&meta.description);
        entries.insert(
            name.to_string(),
            CatalogEntry {
                category: category_for(name).to_string(),
                kind,
                range: None,
                step: None,
                default,
                apply: apply_class_from_csv(cell(apply_col)),
                impact: Impact::Unknown,
                denylist: false,
                gameinfo_ignored: cell(flags_col)
                    .split(',')
                    .any(|f| f.trim() == "gameinfo_cannot_override"),
                notes: description.split_whitespace().collect::<Vec<_>>().join(" "),
                presets,
            },
        );
    }
    Ok(entries)
}

fn apply_class_from_csv(raw: &str) -> ApplyClass {
    if raw == "live" {
        ApplyClass::Live
    } else if raw.starts_with("live w/ sv_cheats") {
        ApplyClass::LiveCheat
    } else {
        ApplyClass::Restart
    }
}

fn infer_kind<'a>(values: impl Iterator<Item = &'a str>) -> Kind {
    let values: Vec<&str> = values
        .map(|v| v.trim_start_matches("//").trim().trim_matches('"'))
        .filter(|v| !v.is_empty())
        .collect();
    let is_word_bool = |v: &str| v.eq_ignore_ascii_case("true") || v.eq_ignore_ascii_case("false");
    if values.is_empty() {
        Kind::String
    } else if values.iter().any(|v| is_word_bool(v))
        && values
            .iter()
            .all(|v| is_word_bool(v) || *v == "0" || *v == "1")
    {
        Kind::Bool
    } else if values.iter().all(|v| v.parse::<i64>().is_ok()) {
        Kind::Int
    } else if values.iter().all(|v| v.parse::<f64>().is_ok()) {
        Kind::Float
    } else {
        Kind::String
    }
}

