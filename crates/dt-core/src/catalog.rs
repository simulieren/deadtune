fn category_for(name: &str) -> &'static str {
    let lower = name.to_ascii_lowercase();
    CATEGORY_RULES
        .iter()
        .find(|(_, needles)| needles.iter().any(|n| lower.contains(n)))
        .map_or("Advanced", |(category, _)| category)
}

#[derive(serde::Deserialize)]
#[serde(rename_all = "snake_case")]
enum CuratedKind {
    Bool,
    Int,
    Float,
    Enum,
    String,
}

/// A per-name overlay in curated.toml; every field is optional and replaces the generated one.
#[derive(serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct Curated {
    category: Option<String>,
    #[serde(rename = "type")]
    kind: Option<CuratedKind>,
    options: Option<Vec<String>>,
    range: Option<[f64; 2]>,
    step: Option<f64>,
    impact: Option<Impact>,
    denylist: Option<bool>,
    notes: Option<String>,
}

impl Curated {
    fn apply_to(self, entry: &mut CatalogEntry) -> Result<(), &'static str> {
        match (self.kind, self.options) {
            (Some(CuratedKind::Enum), Some(options)) if !options.is_empty() => {
                entry.kind = Kind::Enum { options }
            }
            (Some(CuratedKind::Enum), _) => return Err("type = \"enum\" needs non-empty options"),
            (_, Some(_)) => return Err("options only apply to type = \"enum\""),
            (Some(CuratedKind::Bool), None) => entry.kind = Kind::Bool,
            (Some(CuratedKind::Int), None) => entry.kind = Kind::Int,
            (Some(CuratedKind::Float), None) => entry.kind = Kind::Float,
            (Some(CuratedKind::String), None) => entry.kind = Kind::String,
            (None, None) => {}
        }
        if let Some(category) = self.category {
            entry.category = category;
        }
        entry.range = self.range.or(entry.range);
        entry.step = self.step.or(entry.step);
        entry.impact = self.impact.unwrap_or(entry.impact);
        entry.denylist = self.denylist.unwrap_or(entry.denylist);
        if let Some(notes) = self.notes {
            entry.notes = notes;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const CSV: &str = include_str!("../../../research/data/convar_catalog.csv");
    const CURATED: &str = include_str!("../../../catalog/curated.toml");

    fn generated(curated: &str) -> Catalog {
        Catalog::from_toml(&generate(CSV, curated).unwrap()).unwrap()
    }

    #[test]
    fn generate_emits_one_entry_per_csv_row() {
        assert_eq!(generated("").entries.len(), 772);
    }

    #[test]
    fn apply_class_follows_csv_flags() {
        let c = generated("");
        assert_eq!(c.apply_class("fps_max"), ApplyClass::Live);
        assert_eq!(c.apply_class("r_farz"), ApplyClass::LiveCheat);
        assert_eq!(
            c.apply_class("r_citadel_shadow_quality"),
            ApplyClass::Restart,
            "devonly is gameinfo-only"
        );
        assert_eq!(
            c.apply_class("ai_disable"),
            ApplyClass::Restart,
            "unknown flags are treated as restart"
        );
    }

    #[test]
    fn gameinfo_ignored_follows_the_csv_flag() {
        let c = generated("");
        assert!(c.is_gameinfo_ignored("r_shadows"));
        assert!(c.is_gameinfo_ignored("r_citadel_npr_outlines"));
        assert!(!c.is_gameinfo_ignored("r_citadel_shadow_quality"));
        assert!(!c.is_gameinfo_ignored("not_a_convar"));
        assert_eq!(
            c.entries.values().filter(|e| e.gameinfo_ignored).count(),
            37
        );
    }

    #[test]
    fn kind_is_inferred_from_values() {
        let c = generated("");
        assert_eq!(
            c.get("r_ssao").unwrap().kind,
            Kind::Bool,
            "true default with 0 in presets"
        );
        assert_eq!(c.get("fps_max").unwrap().kind, Kind::Int);
        assert_eq!(
            c.get("sc_screen_size_lod_scale_override").unwrap().kind,
            Kind::Float
        );
        assert_eq!(
            c.get("r_particle_max_draw_distance").unwrap().kind,
            Kind::Float,
            "1e+06 default"
        );
    }

    #[test]
    fn default_prefers_engine_then_comment() {
        let c = generated("");
        assert_eq!(c.get("fps_max").unwrap().default.as_deref(), Some("400"));
        assert_eq!(
            c.get("ai_disable").unwrap().default.as_deref(),
            Some("0"),
            "from [def: \"0\"]"
        );
        assert_eq!(c.get("ai_async_queue_max_jobs").unwrap().default, None);
    }

    #[test]
    fn presets_and_notes_come_from_the_csv() {
        let c = generated("");
        let farz = c.get("r_farz").unwrap();
        assert_eq!(
            farz.presets.get(&PresetId::KaizMinspec).map(String::as_str),
            Some("4500")
        );
        assert_eq!(
            farz.presets.get(&PresetId::Vanilla),
            None,
            "empty preset cells are skipped"
        );
        assert_eq!(
            c.get("ai_disable")
                .unwrap()
                .presets
                .get(&PresetId::Sqooky)
                .map(String::as_str),
            Some("//1"),
            "commented values keep their //"
        );
        assert!(
            farz.notes.starts_with("Override the far clipping plane."),
            "{}",
            farz.notes
        );
        assert!(
            c.get("ai_disable")
                .unwrap()
                .notes
                .starts_with("Both of these commands")
        );
    }

    #[test]
    fn category_is_inferred_from_name() {
        let c = generated("");
        assert_eq!(c.get("csm_max_visible_dist").unwrap().category, "Shadows");
        assert_eq!(c.get("panorama_max_fps").unwrap().category, "UI & Panorama");
        assert_eq!(
            c.get("r_particle_max_detail_level").unwrap().category,
            "Particles & effects"
        );
        assert_eq!(
            c.get("this_is_an_example_comment").unwrap().category,
            "Advanced"
        );
    }

    #[test]
    fn curated_overrides_win() {
        let curated = r#"
            [r_farz]
            category = "Custom"
            range = [2000, 16000]
            step = 500
            impact = "high"
            notes = "curated note"
            [fps_max]
            type = "enum"
            options = ["0", "60"]
            [citadel_player_outline_enemies]
            denylist = true
        "#;
        let c = generated(curated);
        let farz = c.get("r_farz").unwrap();
        assert_eq!(farz.category, "Custom");
        assert_eq!(farz.range, Some([2000.0, 16000.0]));
        assert_eq!(farz.step, Some(500.0));
        assert_eq!(farz.impact, Impact::High);
        assert_eq!(farz.notes, "curated note");
        assert_eq!(
            farz.apply,
            ApplyClass::LiveCheat,
            "fields not in the overlay stay generated"
        );
        assert_eq!(
            c.get("fps_max").unwrap().kind,
            Kind::Enum {
                options: vec!["0".into(), "60".into()]
            }
        );
        assert!(c.is_denied("citadel_player_outline_enemies"));
        assert!(!c.is_denied("r_farz"));
    }

    #[test]
    fn curated_rejects_unknown_names_and_fields() {
        assert!(
            generate(CSV, "[r_farzz]\nimpact = \"high\"").is_err(),
            "typo in name"
        );
        assert!(
            generate(CSV, "[r_farz]\nimpakt = \"high\"").is_err(),
            "typo in field"
        );
        assert!(
            generate(CSV, "[r_farz]\ntype = \"enum\"").is_err(),
            "enum without options"
        );
    }

    #[test]
    fn committed_curated_marks_competitive_info_and_perf_convars() {
        let c = generated(CURATED);
        for name in [
            "citadel_player_outline_enemies",
            "citadel_unit_status_allies_see_thru_walls",
            "sv_force_transmit_players",
            "citadel_player_outline_fade_range_min",
            "citadel_player_outline_fade_range_max",
            "r_citadel_selection_outline2_fade_pow",
        ] {
            assert!(c.is_denied(name), "{name} should be denylisted");
        }
        assert!(
            !c.is_denied("citadel_camera_hero_fov"),
            "FOV is a normal setting"
        );
        assert!(
            !c.is_denied("citadel_damage_indicator_radius"),
            "your own hit-direction marker shows nothing about other players"
        );
        let rated = c
            .entries
            .values()
            .filter(|e| e.impact != Impact::Unknown)
            .count();
        assert!(rated >= 55, "only {rated} convars carry an impact rating");
    }

    #[test]
    fn embedded_catalog_matches_a_fresh_generate() {
        let fresh = generate(CSV, CURATED).unwrap();
        assert!(
            include_str!("../../../catalog/catalog.toml") == fresh,
            "catalog/catalog.toml is stale; run `cargo run -p dt-core --example gen_catalog`"
        );
        assert_eq!(Catalog::embedded().entries.len(), 772);
    }

    #[test]
    fn search_is_case_insensitive_over_name_category_and_notes() {
        let c = generated(CURATED);
        let names = |q| c.search(q).map(|(n, _)| n.to_string()).collect::<Vec<_>>();
        assert!(names("R_FARZ").contains(&"r_farz".to_string()));
        assert!(
            names("shadows").contains(&"csm_max_visible_dist".to_string()),
            "category match"
        );
        assert!(
            names("FAR CLIP plane").contains(&"r_farz".to_string()),
            "notes match"
        );
        assert!(names("zzzz-no-such-thing").is_empty());
    }

    #[test]
    fn categories_are_sorted_and_unique() {
        let c = generated(CURATED);
        let cats = c.categories();
        let mut sorted = cats.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(cats, sorted);
        assert!(cats.contains(&"Shadows") && cats.contains(&"Advanced"));
    }
}
